#!/usr/bin/env python3
"""Render documentation assets from captured summary tables, without running evals.

    python3 docs/assets/expectations/render.py
    python3 docs/assets/expectations/render.py --png

CSV snapshots and their provenance come from chartula-evals.
This script only draws them; it makes no model calls and reads no evaluation rubric.
"""
import argparse
import csv
import html
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent
INK, MUTED, GRID = '#26201A', '#62594F', '#E9E2D8'
OPENAI, ANTHROPIC, PARTIAL = '#A86F22', '#128578', '#B34D32'
CASE_LABELS = {'small': 'Small', 'typical': 'Typical', 'large': 'Large', 'difficult': 'Sparse descriptions'}
CONFIGS = [
    ('openai-g-g--gpt-6-luna--gpt-6-luna', 'OpenAI: Luna / Luna'),
    ('openai-g-m--gpt-6-luna--gpt-6.1-sol', 'OpenAI: Luna / Sol'),
    ('openai-m-m--gpt-6.1-sol--gpt-6.1-sol', 'OpenAI: Sol / Sol'),
    ('anthropic-g-g--claude-haiku-5-5--claude-haiku-5-5', 'Anthropic: Haiku / Haiku'),
    ('anthropic-g-m--claude-haiku-5-5--claude-sonnet-5-5', 'Anthropic: Haiku / Sonnet'),
    ('anthropic-m-m--claude-sonnet-5-5--claude-sonnet-5-5', 'Anthropic: Sonnet / Sonnet'),
]


def load(name):
    return list(csv.DictReader((ROOT / name).open(encoding='utf-8')))


def number(row, key):
    return float(row[key]) if row[key] else None


class Chart:
    def __init__(self, height, title, subtitle):
        self.parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="1120" height="{height}" viewBox="0 0 1120 {height}" role="img" aria-labelledby="title description">',
                      '<!-- Generated by render.py from captured measurements; do not edit by hand. -->',
                      f'<title id="title">{html.escape(title)}</title><desc id="description">{html.escape(subtitle)}</desc>',
                      f'<rect width="1120" height="{height}" fill="#FFFDFA"/>',
                      '<style>text{font-family:DejaVu Sans,Arial,sans-serif}</style>']
        self.text(28, 38, title, 25, weight='700')
        self.text(28, 66, subtitle, 14, MUTED)

    def text(self, x, y, value, size=14, color=INK, anchor='start', weight='400'):
        self.parts.append(f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}" fill="{color}" text-anchor="{anchor}" font-weight="{weight}">{html.escape(str(value))}</text>')

    def line(self, x1, y1, x2, y2, color=GRID, width=1):
        self.parts.append(f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{color}" stroke-width="{width}"/>')

    def rect(self, x, y, width, height, color, title):
        self.parts.append(f'<rect x="{x:.1f}" y="{y:.1f}" width="{width:.1f}" height="{height:.1f}" rx="3" fill="{color}"><title>{html.escape(title)}</title></rect>')

    def dot(self, x, y, color, title):
        self.parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="5" fill="{color}"><title>{html.escape(title)}</title></circle>')

    def save(self, name, png):
        target = ROOT / (name + '.svg')
        target.write_text('\n'.join(self.parts) + '\n</svg>\n', encoding='utf-8')
        if png:
            subprocess.run(['rsvg-convert', str(target), '-o', str(target.with_suffix('.png'))], check=True)


def plot_range(chart, row, metric, x, y, width, maximum, color):
    low, med, high = (number(row, metric + s) for s in ['Min', 'Median', 'Max'])
    if med is None:
        chart.text(x, y + 5, 'No complete run', 13, MUTED)
        return
    scale = lambda value: x + value / maximum * width
    chart.line(scale(low), y, scale(high), y, color, 3)
    chart.dot(scale(med), y, color, f'Median {med:g}; observed range {low:g} to {high:g}; {row["complete"]} complete runs')
    value = f'${med:.3f}' if metric == 'uncachedUsd' else f'{med:.0f}s'
    chart.text(x + width + 15, y + 5, value, 14, weight='600')


def axes(chart, x, top, bottom, width, maximum, money):
    for i in range(5):
        xx = x + i / 4 * width
        chart.line(xx, top, xx, bottom)
        chart.text(xx, bottom + 23, f'${maximum * i / 4:.2f}' if money else f'{maximum * i / 4:.0f}s', 12, MUTED, 'middle')


def typical(october, png):
    chart = Chart(440, 'What a typical release cost, and how long it took',
                  '19 pull requests, 17 entries per audience. Technical + customer, with the thorough check on.')
    chart.text(28, 106, 'Rendering model / checking model', 13, MUTED)
    chart.text(290, 106, 'API cost per complete run', 16, weight='600')
    chart.text(745, 106, 'Total elapsed time', 16, weight='600')
    axes(chart, 290, 122, 354, 330, .20, True)
    axes(chart, 745, 122, 354, 275, 60, False)
    for i, (config, label) in enumerate(CONFIGS):
        row = next(r for r in october if r['case'] == 'typical' and r['configuration'] == config)
        y = 145 + i * 38
        color = OPENAI if config.startswith('openai') else ANTHROPIC
        chart.text(28, y + 5, label, 14)
        plot_range(chart, row, 'uncachedUsd', 290, y, 330, .20, color)
        plot_range(chart, row, 'durationSeconds', 745, y, 275, 60, color)
        chart.text(1087, y + 5, f'n={row["complete"]}', 12, MUTED, 'end')
    chart.text(28, 409, 'Dots: median. Lines: observed min-max. Historical USD list prices without cache, 9 Oct 2026.', 13, MUTED)
    chart.save('typical-release', png)


def sizes(october, png):
    chart = Chart(410, 'More source text changes the bill',
                  'Same model for writing and checking, lowest supported thinking. One real release per scenario.')
    chart.dot(35, 98, OPENAI, 'OpenAI Sol / Sol')
    chart.text(48, 103, 'OpenAI Sol / Sol', 13)
    chart.dot(230, 98, ANTHROPIC, 'Anthropic Sonnet / Sonnet')
    chart.text(243, 103, 'Anthropic Sonnet / Sonnet', 13)
    chart.text(290, 135, 'API cost per complete run', 16, weight='600')
    chart.text(745, 135, 'Total elapsed time', 16, weight='600')
    axes(chart, 290, 150, 324, 330, .50, True)
    axes(chart, 745, 150, 324, 275, 120, False)
    for i, (case, description) in enumerate([('small', '8 PRs; 20k description characters'),
                                           ('typical', '19 PRs; 40k description characters'),
                                           ('large', '64 PRs; 169k description characters')]):
        y = 177 + i * 58
        chart.text(28, y, CASE_LABELS[case], 15, weight='600')
        chart.text(28, y + 20, description, 12, MUTED)
        for j, (config, color) in enumerate([(CONFIGS[2][0], OPENAI), (CONFIGS[5][0], ANTHROPIC)]):
            row = next(r for r in october if r['case'] == case and r['configuration'] == config)
            yy = y - 5 + j * 18
            plot_range(chart, row, 'uncachedUsd', 290, yy, 330, .50, color)
            plot_range(chart, row, 'durationSeconds', 745, yy, 275, 120, color)
    chart.text(28, 382, 'Description characters are counted in the saved facts. All shown configurations completed 3/3 runs.', 13, MUTED)
    chart.save('release-size', png)


def completion(october, png):
    chart = Chart(470, 'Did Chartula produce both requested audiences?',
                  'Each square is one run. The number is complete runs out of three; it does not rate the text.')
    chart.text(28, 110, 'Rendering / checking', 13, MUTED)
    cases = ['small', 'typical', 'large', 'difficult']
    for i, case in enumerate(cases):
        chart.text(400 + i * 190, 110, CASE_LABELS[case], 14, anchor='middle', weight='600')
    for i, (config, label) in enumerate(CONFIGS):
        y = 148 + i * 40
        chart.text(28, y + 5, label, 14)
        for j, case in enumerate(cases):
            row = next(r for r in october if r['case'] == case and r['configuration'] == config)
            n = int(row['complete'])
            x = 365 + j * 190
            for k in range(3):
                chart.rect(x + k * 22, y - 10, 17, 20, ANTHROPIC if k < n else PARTIAL,
                           f'{label}, {CASE_LABELS[case]}: {n}/3 complete; {3-n}/3 missing at least one audience')
            chart.text(x + 80, y + 5, f'{n}/3', 14, weight='600')
    chart.rect(28, 395, 17, 17, ANTHROPIC, 'Both audiences rendered')
    chart.text(54, 409, 'Both audiences rendered', 13)
    chart.rect(322, 395, 17, 17, PARTIAL, 'At least one audience did not render')
    chart.text(348, 409, 'At least one audience did not render', 13)
    chart.text(28, 445, 'Sparse-description case: 15 PRs, 10 facts, only 2 facts with a description. October 2026.', 13, MUTED)
    chart.save('completion', png)


def settings(september, png):
    chart = Chart(340, 'What the checking and input settings changed',
                  'September comparison: one release, 19 PRs. Same rendering model, gpt-6-sol, thinking disabled.')
    chart.text(290, 110, 'API cost per complete run', 16, weight='600')
    chart.text(745, 110, 'Total elapsed time', 16, weight='600')
    axes(chart, 290, 124, 244, 330, .12, True)
    axes(chart, 745, 124, 244, 275, 48, False)
    configs = [('gpt-6-sol-disabled', 'Descriptions + thorough check'),
               ('gpt-6-sol-disabled-no-thorough', 'Descriptions, rule-based only'),
               ('gpt-6-sol-disabled-title-only', 'Titles only + thorough check')]
    for i, (config, label) in enumerate(configs):
        row = next(r for r in september if r['configuration'] == config)
        y = 148 + i * 40
        chart.text(28, y + 5, label, 13)
        plot_range(chart, row, 'uncachedUsd', 290, y, 330, .12, OPENAI)
        plot_range(chart, row, 'durationSeconds', 745, y, 275, 48, OPENAI)
    chart.text(28, 308, 'Median and observed range of 3 complete runs. Historical USD prices without cache, 25 Sep 2026.', 13, MUTED)
    chart.save('settings', png)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--png', action='store_true')
    args = parser.parse_args()
    if args.png and not shutil.which('rsvg-convert'):
        parser.error('--png requires rsvg-convert')
    october, september = load('october-summary.csv'), load('september-summary.csv')
    typical(october, args.png)
    sizes(october, args.png)
    completion(october, args.png)
    settings(september, args.png)


if __name__ == '__main__':
    main()
